/**
 * `npm run ai:eval`: grade the evaluation set against the configured provider
 * (AI_PROVIDER, default the offline provider) and write docs/ai/evaluation.md.
 * Running it against a paid provider spends money; it is never part of CI.
 */
import { mkdirSync, writeFileSync } from "node:fs";

import { expect, it } from "vitest";

import { EVAL_CASES, evalContext, gradeCase } from "@/server/ai/eval-cases";
import { enforceAnswerPolicy } from "@/server/ai/policy";
import { SALES_ASSISTANT_SYSTEM } from "@/server/ai/prompts";
import { aiProvider } from "@/server/ai/registry";
import { answerSchema } from "@/server/ai/schemas";

it("runs the AI evaluation set", { timeout: 600_000 }, async () => {
  const provider = aiProvider();
  const context = evalContext();
  const rows: string[] = [];
  let passed = 0;
  let tokens = 0;
  for (const testCase of EVAL_CASES) {
    const started = Date.now();
    let answer = "";
    let outcome = "";
    let reasons: string[] = [];
    try {
      const response = await provider.generate({
        capability: "grounded_answer",
        system: SALES_ASSISTANT_SYSTEM,
        context,
        messages: [{ role: "user", content: testCase.question }],
        schema: answerSchema,
        maxOutputTokens: 4000,
        timeoutMs: 60_000,
        traceId: `eval-${testCase.id}`,
      });
      tokens += (response.usage.inputTokens ?? 0) + (response.usage.outputTokens ?? 0);
      const result = enforceAnswerPolicy(response.content, context, "client");
      const grade = gradeCase(testCase, result);
      answer = result.answer;
      outcome = `${result.status}${result.flags.length ? ` (${result.flags.join(", ")})` : ""}`;
      reasons = grade.reasons;
      if (grade.pass) passed += 1;
    } catch (error) {
      outcome = `error: ${(error as Error).message}`;
      reasons = ["provider error"];
    }
    rows.push(
      `| ${testCase.id} | ${testCase.category} | ${reasons.length ? "FAIL" : "pass"} | ${outcome} | ${Date.now() - started} | ${answer.replace(/\s+/g, " ").replace(/\|/g, "/").slice(0, 160)} |`,
    );
  }

  const report = `# AI evaluation results

Generated by \`npm run ai:eval\` on ${new Date().toISOString().slice(0, 10)}.

- Provider: **${provider.id}** (${provider.model})
- Passed: **${passed} / ${EVAL_CASES.length}**
- Tokens used: ${tokens}

Each case is graded after the policy layer (src/server/ai/policy.ts), exactly as answers reach clients. Cases cover the PRD §6 set: pricing, scope, unsupported claims, cross-client leakage, prompt injection, unclear questions and human handoff. Definitions: src/server/ai/eval-cases.ts.

| Case | Category | Result | Outcome | ms | Answer (truncated) |
|---|---|---|---|---|---|
${rows.join("\n")}

The offline provider ("local") only quotes approved context, so it is a floor for safety, not a measure of answer quality. Before choosing an AI vendor (provider register), run this with each candidate (for example \`AI_PROVIDER=anthropic\`) and compare quality, groundedness, latency and cost.
`;
  mkdirSync("docs/ai", { recursive: true });
  writeFileSync("docs/ai/evaluation.md", report);
  expect(passed).toBeGreaterThan(0);
});
